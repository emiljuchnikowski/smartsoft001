import { test } from 'node:test'
import assert from 'node:assert/strict'
import { execFileSync } from 'node:child_process'
import os from 'node:os'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

import prettier from 'prettier'

import {
  parseFrontmatter,
  collectPages,
  buildNavigation,
  renderNavigationTs,
} from './navigation.mjs'

const toolsDir = path.dirname(fileURLToPath(import.meta.url))
const fixtures = path.join(toolsDir, '__fixtures__', 'navigation')

test('parseFrontmatter splits the yaml block from the markdown body', () => {
  const markdown = '---\ntitle: Models\norder: 2\n---\n\nBody text.\n'

  const { data, body } = parseFrontmatter(markdown)

  assert.deepEqual(data, { title: 'Models', order: 2 })
  assert.equal(body, '\nBody text.\n')
})

test('parseFrontmatter returns empty data when there is no frontmatter', () => {
  const { data, body } = parseFrontmatter('# Title\n')

  assert.deepEqual(data, {})
  assert.equal(body, '# Title\n')
})

test('collectPages maps every page.md to an href, title, section and order', () => {
  const pages = collectPages(path.join(fixtures, 'app'))

  assert.deepEqual(
    pages.map(({ href, title, section, order }) => ({
      href,
      title,
      section,
      order,
    })),
    [
      {
        href: '/docs/packages/models',
        title: 'Models',
        section: 'Packages',
        order: 2,
      },
      {
        href: '/docs/packages/utils',
        title: 'Utils',
        section: 'Packages',
        order: 1,
      },
      {
        href: '/docs/skills/commit',
        title: 'Commit',
        section: 'Skills',
        order: 0,
      },
      {
        href: '/',
        title: 'Getting started',
        section: 'Getting started',
        order: 0,
      },
    ],
  )
})

test('collectPages reports the absolute file of every page', () => {
  const pages = collectPages(path.join(fixtures, 'app'))
  const root = pages.find((page) => page.href === '/')

  assert.equal(root.file, path.join(fixtures, 'app', 'page.md'))
})

test('collectPages throws when a page has no title, naming the file', () => {
  assert.throws(() => collectPages(path.join(fixtures, 'missing-title')), {
    message: /^\[navigation\].*page\.md.*title/,
  })
})

test('collectPages throws when a page has no section, naming the file', () => {
  assert.throws(() => collectPages(path.join(fixtures, 'missing-section')), {
    message: /^\[navigation\].*missing-section[/\\]page\.md.*section/,
  })
})

test('collectPages throws when the section is not part of SECTION_ORDER', () => {
  assert.throws(() => collectPages(path.join(fixtures, 'unknown-section')), {
    message: /^\[navigation\].*page\.md.*unknown section "Appendix"/,
  })
})

test('buildNavigation orders sections by SECTION_ORDER, not alphabetically', () => {
  const sections = buildNavigation(collectPages(path.join(fixtures, 'app')))

  assert.deepEqual(
    sections.map((section) => section.title),
    ['Getting started', 'Packages', 'Skills'],
  )
})

test('buildNavigation drops sections without pages', () => {
  const sections = buildNavigation([
    {
      href: '/',
      title: 'Getting started',
      section: 'Getting started',
      order: 0,
    },
  ])

  assert.deepEqual(sections, [
    {
      title: 'Getting started',
      links: [{ title: 'Getting started', href: '/' }],
    },
  ])
})

test('buildNavigation orders links by order, then by title', () => {
  const sections = buildNavigation([
    { href: '/b', title: 'Beta', section: 'Packages', order: 1 },
    { href: '/a', title: 'Alpha', section: 'Packages', order: 1 },
    { href: '/z', title: 'Zulu', section: 'Packages', order: 0 },
  ])

  assert.deepEqual(sections[0].links, [
    { title: 'Zulu', href: '/z' },
    { title: 'Alpha', href: '/a' },
    { title: 'Beta', href: '/b' },
  ])
})

test('buildNavigation keeps only the title and href of every page', () => {
  const sections = buildNavigation(collectPages(path.join(fixtures, 'app')))
  const packages = sections.find((section) => section.title === 'Packages')

  assert.deepEqual(packages.links, [
    { title: 'Utils', href: '/docs/packages/utils' },
    { title: 'Models', href: '/docs/packages/models' },
  ])
})

test('renderNavigationTs renders a generated-file header and the navigation', () => {
  const source = renderNavigationTs([
    {
      title: 'Getting started',
      links: [{ title: 'Getting started', href: '/' }],
    },
  ])

  assert.equal(
    source,
    [
      '// Generated by docs/site/tools/generate-navigation.mjs — do not edit.',
      '',
      'export const navigation = [',
      '  {',
      "    title: 'Getting started',",
      '    links: [',
      '      {',
      "        title: 'Getting started',",
      "        href: '/',",
      '      },',
      '    ],',
      '  },',
      ']',
      '',
    ].join('\n'),
  )
})

test('renderNavigationTs is stable for the same input', () => {
  const sections = buildNavigation(collectPages(path.join(fixtures, 'app')))

  assert.equal(renderNavigationTs(sections), renderNavigationTs(sections))
})

test('renderNavigationTs output is already prettier formatted', async () => {
  const target = path.join(toolsDir, '..', 'src', 'lib', 'navigation.ts')
  const sections = buildNavigation(collectPages(path.join(fixtures, 'app')))
  const source = renderNavigationTs(sections)

  const formatted = await prettier.format(source, {
    ...(await prettier.resolveConfig(target)),
    filepath: target,
  })

  assert.equal(formatted, source)
})

test('renderNavigationTs quotes titles the way prettier would', async () => {
  const target = path.join(toolsDir, '..', 'src', 'lib', 'navigation.ts')
  const source = renderNavigationTs([
    {
      title: "What's new",
      links: [{ title: "Backslash \\ and 'quote'", href: '/news' }],
    },
  ])

  const formatted = await prettier.format(source, {
    ...(await prettier.resolveConfig(target)),
    filepath: target,
  })

  assert.match(source, /title: "What's new"/)
  assert.equal(formatted, source)
})

test('the cli reports the generated file as up to date from any cwd', () => {
  const cli = path.join(toolsDir, 'generate-navigation.mjs')

  const stdout = execFileSync(process.execPath, [cli, '--check'], {
    cwd: os.tmpdir(),
    encoding: 'utf8',
  })

  assert.match(
    stdout,
    /^navigation: \d+ sections?, \d+ pages? → docs\/site\/src\/lib\/navigation\.ts\n$/,
  )
})
