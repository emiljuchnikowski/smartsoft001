/**
 * Builds the documentation navigation from the frontmatter of every
 * `src/app/**\/page.md`. Pure helpers only: the CLI in
 * `generate-navigation.mjs` owns the file system side effects.
 */
import fs from 'node:fs'
import path from 'node:path'

import yaml from 'js-yaml'

import { SECTION_ORDER } from './sections.mjs'

const FRONTMATTER = /^---\r?\n([\s\S]*?)\r?\n---\r?\n?/

export function parseFrontmatter(markdown) {
  const match = FRONTMATTER.exec(markdown)

  if (!match) return { data: {}, body: markdown }

  return {
    data: yaml.load(match[1]) ?? {},
    body: markdown.slice(match[0].length),
  }
}

function findPageFiles(dir) {
  return fs.readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
    if (entry.isDirectory()) {
      return entry.name === 'node_modules'
        ? []
        : findPageFiles(path.join(dir, entry.name))
    }

    return entry.name === 'page.md' ? [path.join(dir, entry.name)] : []
  })
}

function hrefOf(appDir, file) {
  const relative = path.relative(appDir, path.dirname(file))

  return relative === '' ? '/' : '/' + relative.split(path.sep).join('/')
}

function validate({ file, title, section }) {
  if (!title) {
    throw new Error(`[navigation] ${file}: frontmatter is missing "title"`)
  }

  if (!section) {
    throw new Error(`[navigation] ${file}: frontmatter is missing "section"`)
  }

  if (!SECTION_ORDER.includes(section)) {
    throw new Error(
      `[navigation] ${file}: unknown section "${section}", expected one of ${SECTION_ORDER.map(
        (name) => `"${name}"`,
      ).join(', ')}`,
    )
  }
}

export function collectPages(appDir) {
  return findPageFiles(appDir)
    .sort((a, b) =>
      path.relative(appDir, a).localeCompare(path.relative(appDir, b)),
    )
    .map((file) => {
      const { data } = parseFrontmatter(fs.readFileSync(file, 'utf8'))

      const page = {
        file,
        href: hrefOf(appDir, file),
        title: data.title,
        section: data.section,
        order: data.order ?? 0,
      }

      validate(page)

      return page
    })
}

export function buildNavigation(pages) {
  return SECTION_ORDER.filter((section) =>
    pages.some((page) => page.section === section),
  ).map((section) => ({
    title: section,
    links: pages
      .filter((page) => page.section === section)
      .sort((a, b) => a.order - b.order || a.title.localeCompare(b.title))
      .map(({ title, href }) => ({ title, href })),
  }))
}

const HEADER =
  '// Generated by docs/site/tools/generate-navigation.mjs — do not edit.'

/** Quotes a string the way prettier does with `singleQuote: true`. */
function quote(value) {
  const quoteChar =
    (value.match(/'/g) ?? []).length > (value.match(/"/g) ?? []).length
      ? '"'
      : "'"
  const escaped = value
    .replace(/\\/g, '\\\\')
    .split(quoteChar)
    .join(`\\${quoteChar}`)

  return `${quoteChar}${escaped}${quoteChar}`
}

export function renderNavigationTs(sections) {
  const lines = [HEADER, '', 'export const navigation = [']

  for (const section of sections) {
    lines.push('  {', `    title: ${quote(section.title)},`, '    links: [')

    for (const link of section.links) {
      lines.push(
        '      {',
        `        title: ${quote(link.title)},`,
        `        href: ${quote(link.href)},`,
        '      },',
      )
    }

    lines.push('    ],', '  },')
  }

  lines.push(']', '')

  return lines.join('\n')
}
